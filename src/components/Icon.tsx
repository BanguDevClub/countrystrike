export type IconName = keyof typeof ICONS

interface IconProps {
  name: string
  size?: number
  strokeWidth?: number
  className?: string
  'aria-hidden'?: boolean
}

export function Icon({ name, size = 18, strokeWidth = 1.8, className, ...rest }: IconProps) {
  const Component: LucideIcon = ICONS[name as IconName] ?? Circle
  return (
    <Component
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden={rest['aria-hidden'] ?? true}
    />
  )
}
